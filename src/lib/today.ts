/** "Hoje" no fuso de Brasília, como 'YYYY-MM-DD'. O motor de cronograma recebe isso por parâmetro. */
export function todayInSaoPaulo(now: Date = new Date()): string {
  return new Intl.DateTimeFormat('en-CA', {
    timeZone: 'America/Sao_Paulo',
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
  }).format(now);
}
